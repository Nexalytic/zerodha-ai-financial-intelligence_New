import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen, fireEvent, waitFor } from '@testing-library/react';
import { ComplianceAuditPanel } from '../src/components/compliance/ComplianceAuditPanel';
import * as aiReasoningApi from '../src/api/aiReasoning';
import * as portfolioContextModule from '../src/context/PortfolioContext';
import { AIInsightReport } from '../src/types/aiReasoning';
import { PortfolioResponse } from '../src/types/portfolio';

vi.mock('../src/api/aiReasoning');

describe('ComplianceAuditPanel Component', () => {
  const mockPortfolios: PortfolioResponse[] = [
    {
      id: 'demo-portfolio-1',
      name: 'Demo Indian Bluechip Portfolio',
      description: 'Canonical bluechip portfolio',
      is_sample: true,
      created_at: '2026-10-10T00:00:00Z',
      updated_at: '2026-10-10T00:00:00Z',
      holdings_count: 5,
    },
    {
      id: 'demo-portfolio-2',
      name: 'Second Growth Portfolio',
      description: 'Secondary portfolio',
      is_sample: false,
      created_at: '2026-10-10T00:00:00Z',
      updated_at: '2026-10-10T00:00:00Z',
      holdings_count: 3,
    },
  ];

  const mockVerifiedReport: AIInsightReport = {
    report_id: 'audit-rep-001',
    portfolio_id: 'demo-portfolio-1',
    generated_at: '2026-10-11T08:30:00Z',
    provider_name: 'DETERMINISTIC_DEMO_REASONER',
    model_id: 'deterministic-demo-v1',
    is_simulated: true,
    executive_summary:
      'Executive summary for Demo Indian Bluechip Portfolio with fully grounded assertions.',
    key_drivers: [
      {
        driver_id: 'driver-1',
        driver_type: 'CONCENTRATION',
        title: 'Single-Stock Dominance in RELIANCE',
        statement: 'RELIANCE represents 35.00% of priced equity value.',
        supporting_metric_key: 'concentration.top_holding_weight_percent',
        supporting_metric_value: 35.0,
        source_reference: 'analytics.concentration',
        is_grounded: true,
      },
      {
        driver_id: 'driver-2',
        driver_type: 'SECTOR',
        title: 'High Exposure to Information Technology',
        statement: 'IT sector accounts for 30.00% of portfolio allocation.',
        supporting_metric_key: 'sector_allocations.IT',
        supporting_metric_value: 30.0,
        source_reference: 'analytics.sector',
        is_grounded: true,
      },
    ],
    risk_alerts: [],
    confidence: {
      score: 0.9,
      level: 'HIGH',
      calibration_limitation:
        'Heuristic confidence score calculated from data completeness and quote freshness penalties. This is not a statistically calibrated Bayesian probability distribution.',
      data_quality_discount: 0.05,
      staleness_discount: 0.0,
    },
    review_cards: [],
    uncertainty_and_gaps: [
      'Historical risk metrics are unavailable (data_status: INSUFFICIENT_HISTORY); price volatility and beta are not inferred.',
    ],
    disclaimers: [
      'Financial intelligence for educational and demonstration purposes only. Not SEBI-registered investment advice.',
      'Generated by deterministic heuristic demonstration engine. Not genuine LLM reasoning.',
    ],
    review_status: 'VERIFIED',
    grounding_report: {
      total_claims_checked: 4,
      passed_count: 4,
      flagged_count: 0,
      rejected_count: 0,
      is_acceptable: true,
      findings: [
        {
          check_name: 'SYMBOL_HALLUCINATION_CHECK',
          target_id: 'RELIANCE',
          status: 'PASSED',
          reason: 'Symbol RELIANCE confirmed in verified holdings ledger',
          details: { exchange: 'NSE' },
        },
        {
          check_name: 'CONCENTRATION_NUMERIC_VERACITY',
          target_id: 'driver-1',
          status: 'PASSED',
          reason: 'Claimed 35.0% matches computed top holding weight of 35.0%',
          details: { expected: 35.0, observed: 35.0 },
        },
      ],
    },
  };

  const setupContext = (overrides = {}) => {
    vi.spyOn(portfolioContextModule, 'usePortfolio').mockReturnValue({
      portfolios: mockPortfolios,
      activePortfolio: mockPortfolios[0],
      activePortfolioId: 'demo-portfolio-1',
      setActivePortfolioId: vi.fn(),
      isLoading: false,
      error: null,
      refreshPortfolios: vi.fn(),
      ...overrides,
    });
  };

  beforeEach(() => {
    vi.clearAllMocks();
    setupContext();
  });

  it('renders initial empty state without calling AI insights endpoint automatically', () => {
    render(<ComplianceAuditPanel />);

    expect(
      screen.getByRole('tabpanel', { name: /compliance & audit/i })
    ).toBeInTheDocument();
    expect(screen.getByTestId('compliance-audit-panel')).toBeInTheDocument();
    expect(screen.getByTestId('compliance-empty-state')).toBeInTheDocument();
    expect(screen.getByTestId('run-audit-btn')).toBeInTheDocument();

    // Verifies explicit user action invariant: AI endpoint is NEVER called automatically
    expect(aiReasoningApi.generateAIPortfolioInsights).not.toHaveBeenCalled();
  });

  it('runs grounding audit only on explicit button click and displays report metadata', async () => {
    vi.mocked(aiReasoningApi.generateAIPortfolioInsights).mockResolvedValue(
      mockVerifiedReport
    );

    render(<ComplianceAuditPanel />);

    // Click run audit button
    fireEvent.click(screen.getByTestId('run-audit-btn'));

    expect(aiReasoningApi.generateAIPortfolioInsights).toHaveBeenCalledTimes(1);
    expect(aiReasoningApi.generateAIPortfolioInsights).toHaveBeenCalledWith(
      'demo-portfolio-1',
      { include_news: true, news_limit: 10 }
    );

    await waitFor(() => {
      expect(screen.getByTestId('audit-report-id')).toHaveTextContent(
        'audit-rep-001'
      );
    });

    expect(screen.getByTestId('audit-provider-name')).toHaveTextContent(
      'DETERMINISTIC_DEMO_REASONER'
    );
    expect(screen.getByTestId('audit-simulated-badge')).toHaveTextContent(
      'Simulated Heuristic Intelligence'
    );
    expect(
      screen.getByTestId('compliance-regulatory-notice')
    ).toBeInTheDocument();
  });

  it('accurately displays acceptable report with flagged warnings without labeling as verified', async () => {
    const flaggedReport: AIInsightReport = {
      ...mockVerifiedReport,
      review_status: 'FLAGGED_WITH_WARNINGS',
      grounding_report: {
        total_claims_checked: 5,
        passed_count: 3,
        flagged_count: 2,
        rejected_count: 0,
        is_acceptable: true,
        findings: [
          {
            check_name: 'NUMERICAL_TOLERANCE_CHECK',
            target_id: 'driver-2',
            status: 'FLAGGED',
            reason: 'Metric deviates by 0.8% from exact ledger balance.',
            details: { claimed: 30.8, ledger: 30.0 },
          },
          {
            check_name: 'STALE_PRICE_WARNING',
            target_id: 'INFY',
            status: 'FLAGGED',
            reason: 'Quote served from emergency stale cache.',
            details: { ttl: 0 },
          },
        ],
      },
    };

    vi.mocked(aiReasoningApi.generateAIPortfolioInsights).mockResolvedValue(
      flaggedReport
    );

    render(<ComplianceAuditPanel />);
    fireEvent.click(screen.getByTestId('run-audit-btn'));

    await waitFor(() => {
      expect(
        screen.getByTestId('verification-status-flagged')
      ).toBeInTheDocument();
    });

    // Verifies warning banner is displayed even though is_acceptable is true
    expect(
      screen.getByTestId('flagged-discrepancy-warning')
    ).toBeInTheDocument();
    expect(screen.getByTestId('grounding-is-acceptable')).toHaveTextContent(
      'TRUE'
    );
    expect(screen.getByTestId('grounding-flagged-count')).toHaveTextContent('2');
    expect(screen.getByTestId('grounding-passed-count')).toHaveTextContent('3');

    // Never labeled as fully verified when flagged_count > 0
    expect(
      screen.queryByTestId('verification-status-verified')
    ).not.toBeInTheDocument();
  });

  it('displays prominent rejection warning when rejected_count > 0 or is_acceptable is false', async () => {
    const rejectedReport: AIInsightReport = {
      ...mockVerifiedReport,
      review_status: 'REJECTED',
      grounding_report: {
        total_claims_checked: 4,
        passed_count: 2,
        flagged_count: 1,
        rejected_count: 1,
        is_acceptable: false,
        findings: [
          {
            check_name: 'UNKNOWN_SYMBOL_HALLUCINATION',
            target_id: 'XYZCORP',
            status: 'REJECTED',
            reason: 'Assertion cited symbol XYZCORP not in portfolio.',
            details: { symbol: 'XYZCORP' },
          },
        ],
      },
    };

    vi.mocked(aiReasoningApi.generateAIPortfolioInsights).mockResolvedValue(
      rejectedReport
    );

    render(<ComplianceAuditPanel />);
    fireEvent.click(screen.getByTestId('run-audit-btn'));

    await waitFor(() => {
      expect(
        screen.getByTestId('verification-status-rejected')
      ).toBeInTheDocument();
    });

    expect(
      screen.getByTestId('rejected-prominent-warning')
    ).toBeInTheDocument();
    expect(screen.getByTestId('grounding-is-acceptable')).toHaveTextContent(
      'FALSE'
    );
    expect(screen.getByTestId('grounding-rejected-count')).toHaveTextContent('1');
    expect(
      screen.queryByTestId('verification-status-verified')
    ).not.toBeInTheDocument();
  });

  it('labels report as fully verified only when acceptable, 0 rejected, 0 flagged, and status VERIFIED', async () => {
    vi.mocked(aiReasoningApi.generateAIPortfolioInsights).mockResolvedValue(
      mockVerifiedReport
    );

    render(<ComplianceAuditPanel />);
    fireEvent.click(screen.getByTestId('run-audit-btn'));

    await waitFor(() => {
      expect(
        screen.getByTestId('verification-status-verified')
      ).toBeInTheDocument();
    });

    expect(screen.getByTestId('grounding-is-acceptable')).toHaveTextContent(
      'TRUE'
    );
    expect(screen.getByTestId('grounding-rejected-count')).toHaveTextContent('0');
    expect(screen.getByTestId('grounding-flagged-count')).toHaveTextContent('0');
    expect(
      screen.queryByTestId('rejected-prominent-warning')
    ).not.toBeInTheDocument();
    expect(
      screen.queryByTestId('flagged-discrepancy-warning')
    ).not.toBeInTheDocument();
  });

  it('filters validation findings interactively by status', async () => {
    const multiFindingReport: AIInsightReport = {
      ...mockVerifiedReport,
      grounding_report: {
        total_claims_checked: 3,
        passed_count: 1,
        flagged_count: 1,
        rejected_count: 1,
        is_acceptable: false,
        findings: [
          {
            check_name: 'PASS_CHECK',
            target_id: 'target-1',
            status: 'PASSED',
            reason: 'Passed finding',
          },
          {
            check_name: 'FLAG_CHECK',
            target_id: 'target-2',
            status: 'FLAGGED',
            reason: 'Flagged finding',
          },
          {
            check_name: 'REJECT_CHECK',
            target_id: 'target-3',
            status: 'REJECTED',
            reason: 'Rejected finding',
          },
        ],
      },
    };

    vi.mocked(aiReasoningApi.generateAIPortfolioInsights).mockResolvedValue(
      multiFindingReport
    );

    render(<ComplianceAuditPanel />);
    fireEvent.click(screen.getByTestId('run-audit-btn'));

    await waitFor(() => {
      expect(screen.getByTestId('grounding-findings-table')).toBeInTheDocument();
    });

    // Initial state: ALL findings visible (3 rows)
    expect(
      screen.getByTestId('finding-row-PASS_CHECK-target-1')
    ).toBeInTheDocument();
    expect(
      screen.getByTestId('finding-row-FLAG_CHECK-target-2')
    ).toBeInTheDocument();
    expect(
      screen.getByTestId('finding-row-REJECT_CHECK-target-3')
    ).toBeInTheDocument();

    // Filter by PASSED only
    fireEvent.click(screen.getByTestId('filter-passed'));
    expect(
      screen.getByTestId('finding-row-PASS_CHECK-target-1')
    ).toBeInTheDocument();
    expect(
      screen.queryByTestId('finding-row-FLAG_CHECK-target-2')
    ).not.toBeInTheDocument();
    expect(
      screen.queryByTestId('finding-row-REJECT_CHECK-target-3')
    ).not.toBeInTheDocument();

    // Filter by REJECTED only
    fireEvent.click(screen.getByTestId('filter-rejected'));
    expect(
      screen.queryByTestId('finding-row-PASS_CHECK-target-1')
    ).not.toBeInTheDocument();
    expect(
      screen.getByTestId('finding-row-REJECT_CHECK-target-3')
    ).toBeInTheDocument();
  });

  it('renders grounded key drivers with exact supporting metrics and source references', async () => {
    vi.mocked(aiReasoningApi.generateAIPortfolioInsights).mockResolvedValue(
      mockVerifiedReport
    );

    render(<ComplianceAuditPanel />);
    fireEvent.click(screen.getByTestId('run-audit-btn'));

    await waitFor(() => {
      expect(
        screen.getByTestId('key-drivers-audit-table')
      ).toBeInTheDocument();
    });

    expect(screen.getByTestId('driver-row-driver-1')).toBeInTheDocument();
    expect(screen.getByTestId('driver-grounded-driver-1')).toHaveTextContent(
      'SUPPORTED'
    );
    expect(
      screen.getByText('concentration.top_holding_weight_percent')
    ).toBeInTheDocument();
    expect(screen.getByText('analytics.concentration')).toBeInTheDocument();
  });

  it('displays confidence score, discounts, mandatory calibration limitation, and uncertainty disclosures', async () => {
    vi.mocked(aiReasoningApi.generateAIPortfolioInsights).mockResolvedValue(
      mockVerifiedReport
    );

    render(<ComplianceAuditPanel />);
    fireEvent.click(screen.getByTestId('run-audit-btn'));

    await waitFor(() => {
      expect(
        screen.getByTestId('confidence-limitations-section')
      ).toBeInTheDocument();
    });

    expect(screen.getByTestId('confidence-score-val')).toHaveTextContent('90%');
    expect(screen.getByTestId('confidence-level-tier')).toHaveTextContent('HIGH');
    expect(screen.getByTestId('confidence-data-discount')).toHaveTextContent('-5%');

    // Mandatory calibration limitation disclosure
    const calNotice = screen.getByTestId('calibration-limitation-notice');
    expect(calNotice).toBeInTheDocument();
    expect(calNotice).toHaveTextContent(
      'Heuristic confidence score calculated from data completeness'
    );
    expect(calNotice).toHaveTextContent(
      'not a statistically calibrated Bayesian probability distribution'
    );

    // Uncertainty and gaps list
    expect(
      screen.getByTestId('uncertainty-gap-item-0')
    ).toHaveTextContent('Historical risk metrics are unavailable');
  });

  it('renders recommendation rejection safeguards and legal disclaimers', async () => {
    vi.mocked(aiReasoningApi.generateAIPortfolioInsights).mockResolvedValue(
      mockVerifiedReport
    );

    render(<ComplianceAuditPanel />);
    fireEvent.click(screen.getByTestId('run-audit-btn'));

    await waitFor(() => {
      expect(
        screen.getByTestId('safeguards-and-disclaimers-section')
      ).toBeInTheDocument();
    });

    expect(
      screen.getByText(/Grounding Fail-Safe Policy Invariant/i)
    ).toBeInTheDocument();
    expect(screen.getByTestId('disclaimers-list')).toBeInTheDocument();
    expect(screen.getByTestId('disclaimer-item-0')).toHaveTextContent(
      'Not SEBI-registered investment advice'
    );
  });

  it('renders honest audit trail persistence boundaries disclosure', async () => {
    vi.mocked(aiReasoningApi.generateAIPortfolioInsights).mockResolvedValue(
      mockVerifiedReport
    );

    render(<ComplianceAuditPanel />);
    fireEvent.click(screen.getByTestId('run-audit-btn'));

    await waitFor(() => {
      expect(
        screen.getByTestId('persistence-disclosure-section')
      ).toBeInTheDocument();
    });

    expect(
      screen.getByText(/Audit reports, verification finding logs, and review states are/i)
    ).toBeInTheDocument();
    expect(screen.getByText(/not persisted/i)).toBeInTheDocument();
    expect(
      screen.getByText(/SQLite retains only investment portfolios and asset holdings/i)
    ).toBeInTheDocument();
  });

  it('handles audit API failure with localized error banner and retry capability', async () => {
    vi.mocked(aiReasoningApi.generateAIPortfolioInsights).mockRejectedValue(
      new Error('AI provider connection timeout.')
    );

    render(<ComplianceAuditPanel />);
    fireEvent.click(screen.getByTestId('run-audit-btn'));

    const errorBanner = await screen.findByTestId('compliance-error-banner');
    expect(errorBanner).toBeInTheDocument();
    expect(
      screen.getByText('AI provider connection timeout.')
    ).toBeInTheDocument();

    const retryBtn = screen.getByTestId('retry-audit-btn');
    expect(retryBtn).toBeInTheDocument();

    // Clicking retry invokes API again
    vi.mocked(aiReasoningApi.generateAIPortfolioInsights).mockResolvedValueOnce(
      mockVerifiedReport
    );
    fireEvent.click(retryBtn);

    await waitFor(() => {
      expect(screen.getByTestId('audit-report-id')).toBeInTheDocument();
    });
  });

  it('clears previous report immediately and invalidates in-flight requests on portfolio switch', async () => {
    let resolveFirstPromise: (data: any) => void;
    const firstPromise = new Promise((resolve) => {
      resolveFirstPromise = resolve;
    });

    vi.mocked(aiReasoningApi.generateAIPortfolioInsights).mockReturnValueOnce(
      firstPromise as any
    );

    const { rerender } = render(<ComplianceAuditPanel />);

    // Start audit for first portfolio
    fireEvent.click(screen.getByTestId('run-audit-btn'));
    expect(screen.getByTestId('compliance-loading-state')).toBeInTheDocument();

    // Switch active portfolio in context while request is in flight
    setupContext({
      activePortfolio: mockPortfolios[1],
      activePortfolioId: 'demo-portfolio-2',
    });

    rerender(<ComplianceAuditPanel />);

    // Report and loading state are immediately reset to empty
    expect(screen.getByTestId('compliance-empty-state')).toBeInTheDocument();
    expect(
      screen.queryByTestId('compliance-loading-state')
    ).not.toBeInTheDocument();

    // Late response from first portfolio resolves
    resolveFirstPromise!(mockVerifiedReport);

    // Stale report for previous portfolio is discarded and never mounted
    await waitFor(() => {
      expect(screen.queryByTestId('audit-report-id')).not.toBeInTheDocument();
    });
    expect(screen.getByTestId('compliance-empty-state')).toBeInTheDocument();
  });
});
